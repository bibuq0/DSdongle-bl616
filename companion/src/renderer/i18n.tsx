export type TranslationKey = keyof typeof zh;

type LanguageContextValue = {
  lang: UiLanguage;
  t: (key: TranslationKey) => string;
  setLang: (language: UiLanguage) => void;
};

const LanguageContext = createContext<LanguageContextValue | null>(null);

export function LanguageProvider({ children }: { children: React.ReactNode }): React.JSX.Element {
  const [lang, setLangState] = useState<UiLanguage>('en');

  useEffect(() => {
    void window.bridge
      .getSettings()
      .then((settings) => setLangState(settings.language))
      .catch(() => undefined);
  }, []);

  const value = useMemo<LanguageContextValue>(
    () => ({
      lang,
      t: (key) => (lang === 'zh' ? zh[key] : en[key]),
      setLang: (next) => {
        setLangState(next);
        void window.bridge.setLanguage(next).catch(() => undefined);
      }
    }),
    [lang]
  );

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useI18n(): LanguageContextValue {
  const context = useContext(LanguageContext);
  if (!context) {
    throw new Error('useI18n must be used inside LanguageProvider');
  }
  return context;
}
